"""Generate locally bundled Natural Earth Admin0 paths for the Atlas overlay.

uv run --with pyshp==3.1.6 scripts/build-atlas-boundaries.py

Input is the same public-domain 50m source as the relief builder. The output is
deliberately Admin0 only: current Vietnam Admin1 geometry is not bundled until it
passes the separately recorded source/provenance gate.
"""
from __future__ import annotations

import io
import json
import math
import hashlib
import zipfile
from pathlib import Path

import shapefile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / '.tools' / 'atlas-cartography' / 'ne_50m_admin_0_countries.zip'
TARGET = ROOT / 'apps' / 'mobile' / 'src' / 'atlas' / 'country-boundaries.ts'
MANIFEST = ROOT / 'apps' / 'mobile' / 'assets' / 'atlas' / 'manifest.json'
WORLD_WIDTH = 2048
WORLD_HEIGHT = 1280
SCALE = .94 / (math.pi + 2)


def raw(longitude: float, latitude: float) -> tuple[float, float]:
    lon = math.radians(longitude)
    lat = math.radians(latitude)
    alpha = math.acos(max(-1, min(1, math.cos(lat) * math.cos(lon / 2))))
    sinc = 1 if alpha < 1e-9 else math.sin(alpha) / alpha
    return ((lon * 2 / math.pi + 2 * math.cos(lat) * math.sin(lon / 2) / sinc) / 2,
            (lat + math.sin(lat) / sinc) / 2)


def project(longitude: float, latitude: float) -> tuple[float, float]:
    x, y = raw(longitude, latitude)
    return WORLD_WIDTH * (.5 + x * SCALE), WORLD_HEIGHT * (.5 - y * SCALE * 1.6)


def spaced(points: list[tuple[float, float]]) -> list[tuple[float, float]]:
    """Keep public geometry readable without carrying every 50m source vertex."""
    if len(points) < 4:
        return points
    output = [points[0]]
    for point in points[1:-1]:
        last = output[-1]
        if math.hypot(point[0] - last[0], point[1] - last[1]) >= 1.2:
            output.append(point)
    output.append(points[-1])
    return output


def path(points: list[tuple[float, float]]) -> str | None:
    projected = spaced([project(lon, lat) for lon, lat in points])
    if len(projected) < 2:
        return None
    commands = [f'M{projected[0][0]:.1f},{projected[0][1]:.1f}']
    previous = projected[0]
    for point in projected[1:]:
        # Do not draw an artificial seam across the projection edge.
        if abs(point[0] - previous[0]) > WORLD_WIDTH / 2:
            commands.append(f'M{point[0]:.1f},{point[1]:.1f}')
        else:
            commands.append(f'L{point[0]:.1f},{point[1]:.1f}')
        previous = point
    return ''.join(commands)


manifest = json.loads(MANIFEST.read_text(encoding='utf-8'))
expected_hash = next((entry['sha256'] for entry in manifest.get('sources', []) if entry.get('file') == SOURCE.name), None)
actual_hash = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
if not expected_hash or expected_hash != actual_hash:
    raise RuntimeError(f'Natural Earth Admin0 source hash does not match the relief manifest: expected={expected_hash}, actual={actual_hash}')

with zipfile.ZipFile(SOURCE) as archive:
    stem = next(name[:-4] for name in archive.namelist() if name.endswith('.shp'))
    reader = shapefile.Reader(
        shp=io.BytesIO(archive.read(stem + '.shp')),
        shx=io.BytesIO(archive.read(stem + '.shx')),
        dbf=io.BytesIO(archive.read(stem + '.dbf')),
    )
    boundaries: list[dict[str, object]] = []
    for index, shape in enumerate(reader.shapes()):
        cuts = list(shape.parts) + [len(shape.points)]
        rendered_paths: list[str] = []
        for start, end in zip(cuts[:-1], cuts[1:]):
            rendered = path(shape.points[start:end])
            if rendered:
                rendered_paths.append(rendered)
        if not rendered_paths:
            continue
        source_points = [point for part_start, part_end in zip(cuts[:-1], cuts[1:]) for point in shape.points[part_start:part_end]]
        projected = [project(lon, lat) for lon, lat in source_points]
        boundaries.append({
            'id': f'ne-admin0-{index}',
            'd': ''.join(rendered_paths),
            'minX': round(min(point[0] for point in projected), 1),
            'minY': round(min(point[1] for point in projected), 1),
            'maxX': round(max(point[0] for point in projected), 1),
            'maxY': round(max(point[1] for point in projected), 1),
        })

payload = json.dumps(boundaries, ensure_ascii=False, separators=(',', ':'))
TARGET.write_text(
    "// Generated by scripts/build-atlas-boundaries.py from Natural Earth 50m Admin0.\n"
    "// Public domain source; Admin1 deliberately absent pending current-data verification.\n"
    "export type AtlasCountryBoundary = { id: string; d: string; minX: number; minY: number; maxX: number; maxY: number };\n"
    f"export const ATLAS_COUNTRY_BOUNDARIES: readonly AtlasCountryBoundary[] = {payload};\n"
    f"export const ATLAS_BOUNDARY_SOURCE = {{ version: 'ne-50m-admin0-2026-10-18', sha256: '{actual_hash}', countries: {len(boundaries)}, admin1Coverage: 'unavailable' as const }};\n",
    encoding='utf-8',
)
print(json.dumps({'source': SOURCE.name, 'countries': len(boundaries), 'bytes': TARGET.stat().st_size}))
