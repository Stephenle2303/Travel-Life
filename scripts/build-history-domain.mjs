// Gzip bytes are host-dependent (header OS byte, zlib build), so the check
// compares decompressed JSON and every other byte of the bundle exactly.
function canonicalBundle(text) {
  const match = /^const packedJson = (.*);$/m.exec(text);
  if (!match) throw new Error('HISTORY_DOMAIN_BUNDLE_STALE');
  let packedEntries;
  try {
    packedEntries = Object.entries(JSON.parse(match[1])).map(([id, data]) => [id, gunzipSync(Buffer.from(data, 'base64')).toString('utf8')]);
  } catch {
    throw new Error('HISTORY_DOMAIN_BUNDLE_STALE');
  }
  return text.replace(match[0], () => `const packedJson = ${JSON.stringify(Object.fromEntries(packedEntries))};`);
}
const checkIndex = process.argv.indexOf('--check');
if (checkIndex >= 0) {
  const target = process.argv[checkIndex + 1] ? path.resolve(process.argv[checkIndex + 1]) : destination;
  // A Windows checkout (core.autocrlf) may hold the committed bundle with CRLF.
  const committed = (await readFile(target, 'utf8')).replace(/\r\n?/g, '\n');
  if (canonicalBundle(committed) !== canonicalBundle(bundle)) throw new Error('HISTORY_DOMAIN_BUNDLE_STALE');
} else await writeFile(destination, bundle);
