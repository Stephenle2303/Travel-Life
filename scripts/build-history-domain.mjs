import { gzipSync, gunzipSync } from 'node:zlib';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(path.join(root, 'apps/mobile/package.json'));
const ts = require('typescript');
const modules = new Map();
const sourceRoot = path.join(root, 'apps/mobile/src');
async function visit(file) {
  const id = path.relative(sourceRoot, file).replaceAll('\\', '/');
  if (modules.has(id)) return id;
  if (!file.startsWith(sourceRoot + path.sep)) throw new Error('HISTORY_DOMAIN_EXTERNAL_IMPORT');
  const source = (await readFile(file, 'utf8')).replace(/\r\n?/g, '\n');
  modules.set(id, { source, code: '' });
  if (file.endsWith('.json')) {
    // Keep the complete exact dataset while reducing the Edge upload envelope.
    const compressed = gzipSync(Buffer.from(source.trim(), 'utf8'), { level: 9 }).toString('base64');
    modules.get(id).code = `module.exports = decodedJson[${JSON.stringify(id)}];`;
    modules.get(id).compressed = compressed;
    return id;
  }
  const output = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, esModuleInterop: true } }).outputText;
  const dependencies = [...output.matchAll(/require\("([^"]+)"\)/g)];
  let code = output;
  for (const [, dependency] of dependencies) {
    if (!dependency.startsWith('.')) throw new Error('HISTORY_DOMAIN_NATIVE_IMPORT');
    const target = path.resolve(path.dirname(file), dependency + (dependency.endsWith('.json') ? '' : '.ts'));
    const resolved = await visit(target);
    code = code.replaceAll(`require(${JSON.stringify(dependency)})`, `require(${JSON.stringify(resolved)})`);
  }
  modules.get(id).code = code;
  return id;
}
